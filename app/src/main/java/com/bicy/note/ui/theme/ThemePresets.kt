/**
 * 主题色预设。每个预设包含亮/暗两套品牌色（主色、辅助色、强调色及各自容器色），
 * 中性色（背景、描边、错误色）由 Color.kt 统一提供，不随预设变化。
 */
data class PresetPalette(
    val primary: Color,
    val onPrimary: Color,
    val primaryContainer: Color,
    val onPrimaryContainer: Color,
    val secondary: Color,
    val onSecondary: Color,
    val secondaryContainer: Color,
    val onSecondaryContainer: Color,
    val tertiary: Color,
    val onTertiary: Color,
    val tertiaryContainer: Color,
    val onTertiaryContainer: Color,
)

data class ThemePreset(
    val id: String,
    val name: String,
    val light: PresetPalette,
    val dark: PresetPalette,
)

private fun preset(
    id: String,
    name: String,
    lightPrimary: Color, lightOnPrimary: Color,
    lightPrimaryContainer: Color, lightOnPrimaryContainer: Color,
    lightSecondary: Color, lightOnSecondary: Color,
    lightSecondaryContainer: Color, lightOnSecondaryContainer: Color,
    lightTertiary: Color, lightOnTertiary: Color,
    lightTertiaryContainer: Color, lightOnTertiaryContainer: Color,
    darkPrimary: Color, darkOnPrimary: Color,
    darkPrimaryContainer: Color, darkOnPrimaryContainer: Color,
    darkSecondary: Color, darkOnSecondary: Color,
    darkSecondaryContainer: Color, darkOnSecondaryContainer: Color,
    darkTertiary: Color, darkOnTertiary: Color,
    darkTertiaryContainer: Color, darkOnTertiaryContainer: Color,
): ThemePreset = ThemePreset(
    id = id,
    name = name,
    light = PresetPalette(
        primary = lightPrimary, onPrimary = lightOnPrimary,
        primaryContainer = lightPrimaryContainer, onPrimaryContainer = lightOnPrimaryContainer,
        secondary = lightSecondary, onSecondary = lightOnSecondary,
        secondaryContainer = lightSecondaryContainer, onSecondaryContainer = lightOnSecondaryContainer,
        tertiary = lightTertiary, onTertiary = lightOnTertiary,
        tertiaryContainer = lightTertiaryContainer, onTertiaryContainer = lightOnTertiaryContainer,
    ),
    dark = PresetPalette(
        primary = darkPrimary, onPrimary = darkOnPrimary,
        primaryContainer = darkPrimaryContainer, onPrimaryContainer = darkOnPrimaryContainer,
        secondary = darkSecondary, onSecondary = darkOnSecondary,
        secondaryContainer = darkSecondaryContainer, onSecondaryContainer = darkOnSecondaryContainer,
        tertiary = darkTertiary, onTertiary = darkOnTertiary,
        tertiaryContainer = darkTertiaryContainer, onTertiaryContainer = darkOnTertiaryContainer,
    ),
)

